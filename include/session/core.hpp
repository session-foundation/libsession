/// Wraps a predefined 32-byte account seed to pass to the Core constructor, overriding any seed
/// already stored in the database.  Used when restoring an existing account from a seed.
struct predefined_seed {
    cleared_b32 bytes;
    explicit predefined_seed(std::span<const std::byte, 32> s) {
        std::ranges::copy(s, bytes.begin());
    }
    explicit predefined_seed(std::span<const unsigned char, 32> s) {
        std::ranges::copy(std::as_bytes(s), bytes.begin());
    }

    /// Constructs a predefined_seed from a mnemonic word list.
    ///
    /// Accepts 12 or 13 words (128-bit seed; the upper 16 bytes are set to zero), or 24 or 25
    /// words (256-bit seed).  13- and 25-word inputs include a checksum word which is validated.
    ///
    /// @throws std::invalid_argument if the word count is not 12, 13, 24, or 25.
    /// @throws mnemonics::unknown_word_error if a word is not found in the language dictionary.
    /// @throws mnemonics::checksum_error if the checksum word (if present) does not match.
    explicit predefined_seed(
            std::span<const std::string_view> words, const mnemonics::Mnemonics& lang);
    explicit predefined_seed(
            std::span<const std::string_view> words, std::string_view lang_name = "English");
};

/// Opens the account without inventing an identity for it.
///
/// Ordinarily a Core with no stored seed and no predefined_seed generates one, which gives an
/// application no way to *ask* whether a database already holds an account: finding out has already
/// answered it.  With this option that database opens with no account, globals.have_account()
/// reports which case it is, and the application resolves it with globals.create_account() or
/// globals.restore_account().
///
/// Between construction and that call the account has no identity, so anything needing one --
/// session_id(), account_seed(), send_dm(), attaching a network -- throws no_account.  Nothing
/// else in Core needs it that early: components initialise fine without it and polling does not
/// start until a network is attached.
struct defer_account {};

/// Additional database migrations to apply during Core construction, on behalf of a layer built on
/// top of Core (such as a Client holding conversations and message history in the same database).
///
/// May be passed more than once, and each set is applied in the order given, after all of Core's
/// own migrations.  Two consequences of that ordering:
///
/// - Extension migrations may depend on Core's tables; Core's may never depend on an extension's.
/// - A Core migration added later runs *after* an extension's on an already-populated database,
///   but before it on a fresh one.  Only the rule above makes both orders safe.
///
/// Extension migrations run from apply_migrations(), i.e. before any Core component's init() has
/// run: the Core they are handed is constructed but not yet initialised, so (for example) the
/// account seed is not loaded and globals::session_id() is unavailable.  The layer that supplied
/// them does not exist at all yet.
struct schema_extension {
    /// Distinguishes these migrations from Core's and from other extensions' in the
    /// migrations_applied table.  Must be non-empty, must not contain ':', and must never change
    /// once released: it forms part of the recorded identity of an applied migration, so changing
    /// it re-runs the entire set.
    std::string_view owner;

    /// The migrations themselves.  Not copied, but only referenced while the Core constructor
    /// runs, so this need only outlive construction.
    std::span<const schema::Migration> migrations;

    /// Optional: the schema with every one of the above applied, as generated into the registry's
    /// FULL_SCHEMA.  When a database has none of this owner's migrations applied it is built from
    /// this in one step and they are all recorded without running, which is both faster than
    /// replaying the chain and the reason a readable current schema can exist at all.
    ///
    /// Anything a migration does beyond DDL — seeding rows, say — must therefore also be in here,
    /// since on a fresh database that migration never runs.
    std::string_view full_schema;
};

/// Concept satisfied by any type usable as a Core constructor option: a sqlite database option
/// (encryption, behaviour), or a Core-specific option tag (predefined_seed, callbacks,
/// schema_extension).  All options can be passed in any order after the db_path positional
/// argument.
template <typename T>
concept CoreOption = sqlite::DatabaseOption<std::remove_cvref_t<T>> ||
                     std::same_as<std::remove_cvref_t<T>, predefined_seed> ||
                     std::same_as<std::remove_cvref_t<T>, callbacks> ||
                     std::same_as<std::remove_cvref_t<T>, defer_account> ||
                     std::same_as<std::remove_cvref_t<T>, schema_extension>;

